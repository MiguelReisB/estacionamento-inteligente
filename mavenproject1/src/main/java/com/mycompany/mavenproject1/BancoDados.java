package com.mycompany.mavenproject1;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.io.IOException;
import java.sql.Statement;
import java.sql.PreparedStatement;
import java.sql.ResultSet;

public class BancoDados {

    private static final String URL = "jdbc:h2:file:./dados/estacionamento";
    private static final String USUARIO = "sa";
    private static final String SENHA = "";

public static Connection conectar() throws SQLException {

    try {
        Files.createDirectories(Path.of("./dados"));
    } 
    
    catch (IOException e) {
        throw new SQLException("Não foi possível criar a pasta do banco.", e);
    }

    return DriverManager.getConnection(URL, USUARIO, SENHA);
}

public static void inicializar() throws SQLException {

    String sql = """
    CREATE TABLE IF NOT EXISTS usuarios (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(100) NOT NULL,
        email VARCHAR(150) NOT NULL UNIQUE,
        senha VARCHAR(255) NOT NULL
    )
    """;

    try (Connection conexao = conectar();
         Statement quary = conexao.createStatement()) {

        quary.execute(sql);
    }
}

public static boolean validarLogin(String email, String senha)
        
    throws SQLException {
        String sql = "SELECT 1 FROM usuarios WHERE email = ? AND senha = ?";

    try (Connection conexao = conectar();
         PreparedStatement comando = conexao.prepareStatement(sql)) {

        comando.setString(1, email);
        comando.setString(2, senha);

        try (ResultSet resultado = comando.executeQuery()) {
            return resultado.next();
        }
    }
}

}

